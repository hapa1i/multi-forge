#!/usr/bin/env python3
"""Check or regenerate the installation constraints exported from uv.lock."""

from __future__ import annotations

import argparse
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXPORTS = {
    "runtime.txt": ["--no-dev", "--no-hashes"],
    "build.txt": ["--only-group", "build"],
}


def exported_requirements(root: Path, filename: str, options: list[str]) -> str:
    result = subprocess.run(
        [
            "uv",
            "export",
            "--python",
            sys.executable,
            "--locked",
            "--offline",
            "--no-header",
            "--no-annotate",
            "--no-emit-project",
            *options,
        ],
        cwd=root,
        capture_output=True,
        text=True,
        check=True,
    )
    guarantee = (
        "Exact versions; use uv.lock for artifact hashes." if filename == "runtime.txt" else "Hashed build inputs."
    )
    return f"# Generated by scripts/check-dependency-pins.py --write; do not edit.\n# {guarantee}\n{result.stdout}"


def check(root: Path, *, write: bool = False) -> list[str]:
    project = tomllib.loads((root / "pyproject.toml").read_text())
    if project["build-system"]["requires"] != project["dependency-groups"]["build"]:
        raise ValueError("build-system.requires must match the locked build dependency group")
    stale = []
    for filename, options in EXPORTS.items():
        expected = exported_requirements(root, filename, options)
        if filename == "build.txt":
            build_pins = [
                line.removesuffix(" \\") for line in expected.splitlines() if line and not line.startswith(("#", " "))
            ]
            if sorted(project["tool"]["uv"]["build-constraint-dependencies"]) != sorted(build_pins):
                raise ValueError("tool.uv.build-constraint-dependencies must match the exported build graph")
        path = root / "requirements" / filename
        if write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
        elif not path.is_file() or path.read_text() != expected:
            stale.append(str(path.relative_to(root)))
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Regenerate constraints after reviewing uv.lock changes")
    args = parser.parse_args()
    try:
        stale = check(ROOT, write=args.write)
    except subprocess.CalledProcessError as error:
        print(f"Cannot export the reviewed lock: {error.stderr.strip()}", file=sys.stderr)
        return 1
    except (OSError, ValueError, KeyError) as error:
        print(f"Cannot check dependency pins: {error}", file=sys.stderr)
        return 1
    if stale:
        print(
            f"Stale dependency constraints: {', '.join(stale)}. "
            "Review uv.lock, then run python scripts/check-dependency-pins.py --write.",
            file=sys.stderr,
        )
        return 1
    print("Dependency constraints match uv.lock.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
